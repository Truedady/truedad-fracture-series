const inside = (x: number, y: number, poly: [number, number][]) => {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};

export const MAP_SCALE = 5; // пикселей на градус
export const mapXY = (lon: number, lat: number) => ({x: (lon + 180) * MAP_SCALE, y: (84 - lat) * MAP_SCALE});
export const MAP_W = 360 * MAP_SCALE;
export const MAP_H = 140 * MAP_SCALE;

export const LAND_DOTS: {x: number; y: number; lon: number; lat: number}[] = (() => {
  const out: {x: number; y: number; lon: number; lat: number}[] = [];
  const step = 2.6;
  for (let lat = 82; lat > -56; lat -= step) {
    for (let lon = -178; lon < 180; lon += step) {
      if (POLYS.some((p) => inside(lon, lat, p))) out.push({...mapXY(lon, lat), lon, lat});
    }
  }
  return out;
})();
